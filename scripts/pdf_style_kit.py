def section(s, num, text):
    """Accent banner section header: white text on a crimson strip."""
    p = Paragraph(text.upper(), s['banner'])
    t = Table([[p]], colWidths=[page_geometry()[2]],
              style=TableStyle([
                  ('BACKGROUND', (0, 0), (-1, -1), ACCENT),
                  ('LEFTPADDING', (0, 0), (-1, -1), 10),
                  ('RIGHTPADDING', (0, 0), (-1, -1), 10),
                  ('TOPPADDING', (0, 0), (-1, -1), 5),
                  ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
              ]), hAlign='CENTER')
    return [Spacer(1, 12), t, Spacer(1, 8)]


def make_table(rows, ratios, header=True, align_map=None, small=False):
    """rows: list of lists of Paragraphs. ratios sum to 1.0."""
    _, _, avail = page_geometry()
    widths = [r * avail for r in ratios]
    cmds = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('BOX', (0, 0), (-1, -1), 0.75, ACCENT),
        ('LINEBELOW', (0, 0), (-1, -1), 0.25, TEXT_MUTED),
    ]
    if header:
        cmds += [('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
                 ('LINEBELOW', (0, 0), (-1, 0), 0.75, ACCENT)]
        for i in range(1, len(rows)):
            if i % 2 == 0:
                cmds.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_ODD))
            else:
                cmds.append(('BACKGROUND', (0, i), (-1, i), TABLE_ROW_EVEN))
    t = Table(rows, colWidths=widths, style=TableStyle(cmds), hAlign='CENTER')
    t.repeatRows = 1 if header else 0
    return t


def kpi_row(items, s):
    """items: [(value, label), ...] -> one row of stat callout boxes."""
    boxes = []
    for val, lab in items:
        box = Table(
            [[Paragraph('<b>%s</b>' % val, s['stat'])],
             [Paragraph(lab, s['statlabel'])]],
            colWidths=[(page_geometry()[2] - 20) / len(items)],
            style=TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), BG_PAGE),
                ('BOX', (0, 0), (-1, -1), 0.9, ACCENT),
                ('TOPPADDING', (0, 0), (-1, 0), 9),
                ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
                ('TOPPADDING', (0, 1), (-1, 1), 1),
                ('BOTTOMPADDING', (0, 0), (-1, 0), 1),
            ]))
        boxes.append(box)
    wrap = Table([boxes], colWidths=[page_geometry()[2] / len(items)] *
                 len(items), hAlign='CENTER',
                 style=TableStyle([
                     ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                     ('LEFTPADDING', (0, 0), (-1, -1), 0),
                     ('RIGHTPADDING', (0, 0), (-1, -1), 0),
                     ('TOPPADDING', (0, 0), (-1, -1), 0),
                     ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
                 ]))
    return wrap


def h2(text, s):
    return [Paragraph('<b>%s</b>' % text, s['h2']),
            HRFlowable(width='100%', thickness=0.6, color=ACCENT,
                       spaceBefore=0, spaceAfter=6)]


